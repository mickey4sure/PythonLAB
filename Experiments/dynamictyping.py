# Program to demonstrate Dynamic Typing

# 1. Assign an Integer
var = 100
print(f"Value: {var}, Type: {type(var)}")

# 2. Re-assign the SAME variable to a String
var = "Python Programming"
print(f"Value: {var}, Type: {type(var)}")

# 3. Re-assign the SAME variable to a Float
var = 99.99
print(f"Value: {var}, Type: {type(var)}")

# 4. Re-assign the SAME variable to a List
var = [1, 2, 3]
print(f"Value: {var}, Type: {type(var)}")
