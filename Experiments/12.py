# 12.WAP to perform type conversion or casting in python programming like implicit conversion and explicit conversion.
# Implicit conversion
a = 10
b = 5.5
c = a + b
print("Value of c (implicit conversion):", c, "Type of c:", type(c))
# Explicit conversion
x = 10
y = float(x)
print("Value of y (explicit conversion):", y, "Type of y:", type(y))
